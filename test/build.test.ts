import { readdirSync, readFileSync } from "node:fs";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";
import { buildPackage } from "../scripts/build-package.ts";

const dist = fileURLToPath(new URL("../dist/", import.meta.url));

// Every file under a folder, by its path inside it, with its content.
function files(root: string): Record<string, string> {
  return Object.fromEntries(
    readdirSync(root, { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => {
        const path = join(entry.parentPath, entry.name);
        return [relative(root, path), readFileSync(path, "utf8")];
      }),
  );
}

// dist/ is generated by make build (decision 0063), and kept in the repository so the app can install any commit.
it("keeps dist/ up to date with src/", async () => {
  const fresh = await mkdtemp(join(tmpdir(), "dist-"));

  buildPackage(fresh);

  expect(files(dist), "dist/ is out of date: run make build").toEqual(
    files(fresh),
  );
});
